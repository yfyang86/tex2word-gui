#!/usr/bin/env python3
"""Build app/static/symbols.svg — an SVG sprite of the editor's LaTeX symbols.

The symbol list lives in app/static/symbols.js (the single source, also used by
the browser). Each symbol's glyph is drawn as outline paths taken from a math
font, so previews look the same in every browser and need no web font.

    uv run --no-project --with fonttools python scripts/build_symbols.py FONT

FONT is any OpenType/WOFF math font with wide Unicode coverage; the committed
sprite uses STIX Two Math (SIL Open Font License 1.1), e.g. the
``stix-two-math-*.woff`` file from the ``@fontsource/stix-two-math`` npm
package. Requires node (to read symbols.js) and fontTools.
"""

from __future__ import annotations

import json
import subprocess
import sys
import unicodedata
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
SYMBOLS_JS = ROOT / "app" / "static" / "symbols.js"
OUT = ROOT / "app" / "static" / "symbols.svg"
PAD = 60  # font units around each glyph


def load_symbols() -> list[dict]:
    script = f"process.stdout.write(JSON.stringify(require({json.dumps(str(SYMBOLS_JS))}).LIST))"
    return json.loads(subprocess.check_output(["node", "-e", script], text=True))


def symbol_id(cmd: str) -> str:
    """Mirror of symbolId() in symbols.js."""
    return "s-" + "".join(c if c.isascii() and c.isalnum() else f"_{ord(c):x}" for c in cmd)


def draw(font: TTFont, text: str) -> tuple[str, tuple[float, float, float, float]]:
    """SVG path data (y down) and its bounds for ``text``; combining marks are
    centred above the preceding glyph."""
    cmap, gs, hmtx = font.getBestCmap(), font.getGlyphSet(), font["hmtx"]
    paths, boxes = [], []
    x = 0.0
    prev_box = None
    for ch in text:
        name = cmap.get(ord(ch))
        if name is None:
            raise KeyError(f"glyph for U+{ord(ch):04X} ({ch}) is missing from the font")
        glyph = gs[name]
        bp = BoundsPen(gs)
        glyph.draw(bp)
        gb = bp.bounds or (0, 0, 0, 0)
        if unicodedata.combining(ch) and prev_box is not None:
            # centre over the base glyph, sitting just above it
            dx = (prev_box[0] + prev_box[2]) / 2 - (gb[0] + gb[2]) / 2
            dy = max(0.0, prev_box[3] + 40 - gb[1])
            ox, oy = dx, dy
            adv = 0
        else:
            ox, oy = x, 0.0
            adv = hmtx[name][0]
        pen = SVGPathPen(gs, ntos=lambda v: f"{v:.0f}")
        glyph.draw(TransformPen(pen, (1, 0, 0, -1, ox, -oy)))  # flip y for SVG
        paths.append(pen.getCommands())
        box = (gb[0] + ox, gb[1] + oy, gb[2] + ox, gb[3] + oy)
        boxes.append(box)
        if not unicodedata.combining(ch):
            prev_box = box
        x += adv
    xmin = min(b[0] for b in boxes)
    ymin = min(b[1] for b in boxes)
    xmax = max(b[2] for b in boxes)
    ymax = max(b[3] for b in boxes)
    return " ".join(p for p in paths if p), (xmin, ymin, xmax, ymax)


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    font = TTFont(argv[1])
    upm = font["head"].unitsPerEm
    asc, desc = font["hhea"].ascent, font["hhea"].descent
    symbols = load_symbols()
    out = [
        '<svg xmlns="http://www.w3.org/2000/svg" style="display:none">',
        "<!-- Generated by scripts/build_symbols.py from app/static/symbols.js. Glyph outlines:",
        "     STIX Two Math, (c) 2001-2021 The STIX Fonts Project Authors, SIL Open Font License 1.1. -->",
    ]
    seen = set()
    for s in symbols:
        sid = symbol_id(s["cmd"])
        if sid in seen:
            continue
        seen.add(sid)
        d, (x0, y0, x1, y1) = draw(font, s["glyph"])
        # a common vertical frame keeps relative sizes; widen it for big glyphs
        top = max(y1, asc * 0.82) + PAD
        bottom = min(y0, desc * 0.6) - PAD
        height = top - bottom
        cx = (x0 + x1) / 2
        width = max(x1 - x0 + 2 * PAD, height)
        vb = f"{cx - width / 2:.0f} {-top:.0f} {width:.0f} {height:.0f}"
        out.append(f'<symbol id="{sid}" viewBox="{vb}"><path fill="currentColor" d="{d}"/></symbol>')
    out.append("</svg>")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(seen)} symbols, {OUT.stat().st_size // 1024} KB (upm {upm})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
